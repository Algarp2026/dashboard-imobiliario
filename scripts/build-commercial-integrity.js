'use strict';
const fs=require('node:fs'),path=require('node:path'),{createHash}=require('node:crypto');
const root=path.resolve(__dirname,'..'),target=path.join(root,'google_commercial_integrity.gs');
function build(){
  const sources=['commercial-opportunities.js','commercial-client-workflow.js','server/commercial-integrity.js'];
  const code=sources.map(file=>fs.readFileSync(path.join(root,file),'utf8').replace(/\r\n/g,'\n').trim());
  const hash=createHash('sha256').update(code.join('\n')).digest('hex');
  return '// Generated by scripts/build-commercial-integrity.js; do not edit.\n// Shared audited sources SHA-256: '+hash+'\n'+
    'var THE_VIEW_COMMERCIAL_INTEGRITY = (function() {\n'+
    '  var opportunities, workflow;\n'+
    '  function load(factory) {\n    var module = {exports:{}};\n'+
    '    function resolve(name) {\n'+
    "      if (name === './commercial-opportunities.js' || name === '../commercial-opportunities.js') return opportunities;\n"+
    "      if (name === '../commercial-client-workflow.js') return workflow;\n"+
    "      throw new Error('COMMERCIAL_VALIDATION_UNAVAILABLE');\n    }\n"+
    '    factory(module, module.exports, resolve);\n    return module.exports;\n  }\n'+
    '  opportunities = load(function(module, exports, require) {\n'+code[0]+'\n  });\n'+
    '  workflow = load(function(module, exports, require) {\n'+code[1]+'\n  });\n'+
    '  var integrity = load(function(module, exports, require) {\n'+code[2]+'\n  });\n'+
    '  return {version:1, validate:integrity.validate};\n})();\n';
}
if(require.main===module){const expected=build();if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==expected)throw Error('Commercial integrity bundle is stale');console.log('Commercial integrity bundle matches shared sources')}else{fs.writeFileSync(target,expected);console.log('Generated google_commercial_integrity.gs')}}
module.exports={build};
