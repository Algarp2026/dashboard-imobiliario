'use strict';
const assert=require('node:assert/strict');
const ui=require('../commercial-client-workspace.js');
const clients=[{id:'historical',updatedAt:'2099-01-01'},{id:'old',createdAt:'2026-01-01',stage:'Qualified'},{id:'imported',createdAt:'2026-10-01',majucaImportKey:'fixture'},{id:'new',createdAt:'2026-09-01',stage:'New'}];
const before=JSON.stringify(clients),ids=(mode,extra={})=>ui.sortClients(clients,{mode,...extra}).map(c=>c.id);
assert.deepEqual(ids('newest'),['new','old','imported','historical']);
assert.deepEqual(ids('oldest'),['old','new','historical','imported']);
assert.equal(ui.creationTime({id:'client-1790000000000',updatedAt:'2026-10-01'}),null);
assert.equal(ui.creationTime({createdAt:'2026-10-01',createdByMigration:true}),null);
assert.equal(ui.dateValue('2026-02-30'),null);
assert.equal(ui.dateValue('31/02/2026'),null);
assert.equal(ui.dateValue('01/02/2026'),Date.parse('2026-02-01'));
const contact=new Map([['old',{lastContact:'2026-01-01'}],['new',{lastContact:'2026-10-01'}]]);
assert.deepEqual(ids('contact-recent',{contact}),['new','old','imported','historical']);
assert.deepEqual(ids('contact-oldest',{contact}),['imported','historical','old','new']);
assert.deepEqual(ids('next-action',{actions:new Map([['old',{date:'2026-11-01'}],['new',{date:'2026-10-01'}],['historical',{step:'Review'}]])}),['new','old','historical','imported']);
const filtered=ui.sortClients([clients[0],clients[1]],{mode:'newest',source:clients});
assert.deepEqual(filtered.map(c=>c.id),['old','historical']);
const agents=[{id:'a'},{id:'b'}];
assert.equal(ui.associatedAgentId({agentId:'a'},agents),'a');
assert.equal(ui.associatedAgentId({responsibleAgentId:'b'},agents),'b');
assert.equal(ui.associatedAgentId({agentId:'a',responsibleAgentId:'b'},agents),null);
assert.equal(ui.associatedAgentId({agentId:'missing'},agents),null);
assert.equal(ui.associatedAgentId({notes:'Agency a',origin:'a',agent:'a'},agents),null);
assert.equal(JSON.stringify(clients),before);
console.log('Client workspace PASS: six sort modes, reliable dates, stable historical fallback, filter independence, explicit agent links and no mutations.');
